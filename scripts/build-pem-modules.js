#!/usr/bin/env node
/**
 * Post-`tsc` step (`npm run build` runs it as `postbuild`).
 *
 * Source files import certificate bundles directly
 * (`import rdsCaBundle from './rds-global-bundle.pem'`). The esbuild bundles
 * (SAM template, `npm run package`) inline them with `--loader:.pem=text`,
 * and jest maps them to a stub. `tsc` emits a plain `require('./x.pem')`,
 * which Node cannot load, so the compiled `dist/` failed at load time.
 *
 * For every `.pem` under `src/` this writes `dist/<same path>.pem.js`, a
 * CommonJS module whose export is the file's exact text. Node resolves
 * `require('./x.pem')` to `x.pem.js` (no `x.pem` is copied into `dist/`), so
 * the compiled code gets the same string the bundle inlines: TLS
 * verification is unchanged.
 */

'use strict';

const fs = require('fs');
const path = require('path');

/** Every `.pem` file under `dir`, as paths relative to `dir` */
function findPemFiles(dir, prefix = '') {
  const found = [];
  for (const entry of fs.readdirSync(path.join(dir, prefix), { withFileTypes: true })) {
    const relative = path.join(prefix, entry.name);
    if (entry.isDirectory()) {
      found.push(...findPemFiles(dir, relative));
    } else if (entry.isFile() && entry.name.endsWith('.pem')) {
      found.push(relative);
    }
  }
  return found;
}

/** Write one `<name>.pem.js` string module per `.pem` file; returns the files written */
function writePemModules(srcRoot, outRoot) {
  const written = [];
  for (const relative of findPemFiles(srcRoot)) {
    const text = fs.readFileSync(path.join(srcRoot, relative), 'utf8');
    const outFile = path.join(outRoot, `${relative}.js`);
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(
      outFile,
      `'use strict';\n// Generated by scripts/build-pem-modules.js from src/${relative.split(path.sep).join('/')}. Do not edit.\nmodule.exports = ${JSON.stringify(text)};\n`
    );
    written.push(outFile);
  }
  return written;
}

module.exports = { findPemFiles, writePemModules };

if (require.main === module) {
  const root = path.join(__dirname, '..');
  writePemModules(path.join(root, 'src'), path.join(root, 'dist'));
}
